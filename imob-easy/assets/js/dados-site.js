/* ==========================================================================
   Busca os imóveis de verdade na API que lê o naydb (banco da VPS).
   Se a API não responder (offline, CORS, endereço errado em config.js), o
   conteúdo estático acima continua na tela -- nunca fica em branco.
   ========================================================================== */
(function () {
  "use strict";
  if (!window.API_BASE) return;

  function buscar(caminho) {
    return fetch(window.API_BASE + caminho)
      .then(function (r) { return r.ok ? r.json() : null; })
      .catch(function () { return null; }); // API fora do ar: fica no estático
  }

  Promise.all([
    buscar("/api/imoveis?finalidade=venda&limit=30"),
    buscar("/api/imoveis?finalidade=aluguel&limit=30"),
  ]).then(function (resultados) {
    var comprar = resultados[0];
    var alugar = resultados[1];
    if (comprar) window.DADOS_SITE.comprar = comprar;
    if (alugar) window.DADOS_SITE.alugar = alugar;
    // destaques: os dois imóveis à venda com mais fotos cadastradas
    if (comprar && comprar.length) {
      window.DADOS_SITE.destaques = comprar
        .slice()
        .sort(function (a, b) { return (b.pontos || 0) - (a.pontos || 0); })
        .slice(0, 2);
    }
    if (comprar || alugar) {
      document.dispatchEvent(new CustomEvent("dados-site-atualizados"));
    }
  });
})();
